// Builds extension/README.md (the Marketplace page) from the repository README: absolute image
// and document links, and without the build-from-source section. Run before packaging.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = "https://github.com/Gigi-Didberidze/compass";
const raw = "https://raw.githubusercontent.com/Gigi-Didberidze/compass/main";
let md = readFileSync(join(here, "..", "README.md"), "utf8");
md = md.replace(/\]\(docs\/images\//g, `](${raw}/docs/images/`);
md = md.replace(/\]\((DECISIONS|PROGRESS)\.md\)/g, `](${repo}/blob/main/$1.md)`);
md = md.replace(/## Building from source[\s\S]*?(?=\n## )/, `## Source\n\n${repo}\n`);
const out = `<!-- GENERATED by extension/readme.mjs from ../README.md. Do not edit. -->\n${md}`;
if (process.argv.includes("--check")) {
  if (readFileSync(join(here, "README.md"), "utf8") !== out) {
    console.error("extension/README.md is stale: run node extension/readme.mjs");
    process.exit(1);
  }
} else writeFileSync(join(here, "README.md"), out);
